/**
 * A mouthful of the dead's gibberish: `words` words of one to three syllables each, now and then
 * drawn out, broken off ("..." or "—"), or with a real scrap from UNDEAD.moan surfacing among them.
 * `rand` is any () => [0, 1) (a seeded one gives the same mutter every time).
 */
export function gibberish(rand = Math.random, words = 3 + Math.floor(rand() * 4)) {
  const pick = (a) => a[Math.min(a.length - 1, Math.floor(rand() * a.length))];
  const n = Math.max(1, words | 0);
  const real = rand() < 0.3 ? Math.floor(rand() * n) : -1;   // the one real scrap, if any
  let s = rand() < 0.2 ? '...' : '';
  for (let i = 0; i < n; i++) {
    let w = '';
    if (i === real) w = pick(UNDEAD.moan).replace(/^[.\s]+|[.\s]+$/g, '');
    else {
      const r = rand();   // one syllable, two, now and then three
      for (let k = r < 0.5 ? 1 : r < 0.85 ? 2 : 3; k > 0; k--) w += pick(UNDEAD_SYLLABLES);
      if (rand() < 0.15) w += w[w.length - 1].repeat(1 + Math.floor(rand() * 3));   // drawn out
    }
    if (i > 0) { const r = rand(); s += r < 0.16 ? '... ' : r < 0.24 ? '— ' : ' '; }
    s += w;
  }
  return rand() < 0.35 ? s + '...' : s;
}

